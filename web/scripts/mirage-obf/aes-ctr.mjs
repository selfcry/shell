const RCON = new Uint8Array([0, 1, 2, 4, 8, 16, 32, 64, 128, 27, 54]);

function xtime(a) {
  a &= 255;
  return ((a << 1) ^ ((a >>> 7) * 0x1b)) & 255;
}

function expandKey(key) {
  // key: 32 bytes → 60 uint32 words (AES-256)
  const Nk = 8;
  const Nb = 4;
  const Nr = 14;
  const w = new Uint32Array(Nb * (Nr + 1));
  for (let i = 0; i < Nk; i++) {
    w[i] =
      ((key[4 * i] << 24) |
        (key[4 * i + 1] << 16) |
        (key[4 * i + 2] << 8) |
        key[4 * i + 3]) >>>
      0;
  }
  for (let i = Nk; i < Nb * (Nr + 1); i++) {
    let t = w[i - 1];
    if (i % Nk === 0) {
      t =
        (((SBOX[(t >>> 16) & 255] << 24) |
          (SBOX[(t >>> 8) & 255] << 16) |
          (SBOX[t & 255] << 8) |
          SBOX[t >>> 24]) ^
          (RCON[(i / Nk) | 0] << 24)) >>>
        0;
    } else if (i % Nk === 4) {
      t =
        ((SBOX[t >>> 24] << 24) |
          (SBOX[(t >>> 16) & 255] << 16) |
          (SBOX[(t >>> 8) & 255] << 8) |
          SBOX[t & 255]) >>>
        0;
    }
    w[i] = (w[i - Nk] ^ t) >>> 0;
  }
  return w;
}

function encryptBlock(w, inp) {
  const Nb = 4;
  const Nr = 14;
  const s = new Uint8Array(16);
  for (let c = 0; c < 16; c++) {
    s[c] = inp[c] ^ ((w[c >> 2] >>> ((3 - (c & 3)) * 8)) & 255);
  }
  for (let r = 1; r < Nr; r++) {
    for (let c = 0; c < 16; c++) s[c] = SBOX[s[c]];
    let a0 = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = a0;
    a0 = s[2];
    let a1 = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = a0;
    s[14] = a1;
    a0 = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = a0;
    for (let c = 0; c < 4; c++) {
      const p0 = s[4 * c];
      const p1 = s[4 * c + 1];
      const p2 = s[4 * c + 2];
      const p3 = s[4 * c + 3];
      const u = p0 ^ p1 ^ p2 ^ p3;
      s[4 * c] ^= u ^ xtime(p0 ^ p1);
      s[4 * c + 1] ^= u ^ xtime(p1 ^ p2);
      s[4 * c + 2] ^= u ^ xtime(p2 ^ p3);
      s[4 * c + 3] ^= u ^ xtime(p3 ^ p0);
    }
    for (let c = 0; c < 16; c++) {
      s[c] ^= ((w[r * Nb + (c >> 2)] >>> ((3 - (c & 3)) * 8)) & 255);
    }
  }
  for (let c = 0; c < 16; c++) s[c] = SBOX[s[c]];
  let a0 = s[1];
  s[1] = s[5];
  s[5] = s[9];
  s[9] = s[13];
  s[13] = a0;
  a0 = s[2];
  let a1 = s[6];
  s[2] = s[10];
  s[6] = s[14];
  s[10] = a0;
  s[14] = a1;
  a0 = s[15];
  s[15] = s[11];
  s[11] = s[7];
  s[7] = s[3];
  s[3] = a0;
  for (let c = 0; c < 16; c++) {
    s[c] ^= ((w[Nr * Nb + (c >> 2)] >>> ((3 - (c & 3)) * 8)) & 255);
  }
  return s;
}

export function aes256Ctr(key, nonce, data) {
  const w = expandKey(key);
  const out = new Uint8Array(data.length);
  const ctr = new Uint8Array(16);
  ctr.set(nonce.subarray(0, Math.min(16, nonce.length)));
  for (let i = 0; i < data.length; i += 16) {
    const block = encryptBlock(w, ctr);
    for (let j = 0; j < 16 && i + j < data.length; j++) {
      out[i + j] = data[i + j] ^ block[j];
    }
    for (let j = 15; j >= 0; j--) {
      const x = ctr[j] + 1;
      ctr[j] = x & 255;
      if (x < 256) break;
    }
  }
  return out;
}

